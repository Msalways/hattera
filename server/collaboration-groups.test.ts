import { existsSync, mkdtempSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, expect, it } from "vitest";
import { Store } from "./store.ts";
import { DATA_DIR } from "./config.ts";
import { CollaborationService } from "./collaboration-service.ts";
import { CollaborationGroups } from "./collaboration-groups.ts";
import { removeTempDir } from "./testing/cleanup.ts";
import type { PrivateNetworkState } from "../shared/private-network.ts";

const dirs: string[] = [], close: Array<() => void> = [];
beforeEach(async () => {
  if (!DATA_DIR.startsWith(join(tmpdir(), "omb-test-home-"))) throw new Error("Group projection tests require the isolated Vitest home.");
  await removeTempDir(DATA_DIR);
});
afterEach(async () => { close.splice(0).forEach(fn => fn()); await Promise.all(dirs.splice(0).map(removeTempDir)); });
it("keeps the local app usable when its separate collaboration identity needs repair", async () => {
  const store = new Store(() => ({ instanceId: "fixture", model: "fixture" }));
  const group = store.createGroup("Still a local group", [], false, undefined, { completed: true });
  const network = { async status(): Promise<PrivateNetworkState> { return { available: true, enabled: true, state: "connected", authorizationUrl: null, origin: "http://100.64.2.1", message: null, peers: [], peerTransport: true }; }, async peer() { throw new Error("No peer configured"); } };
  const original = new CollaborationService({ dataDir: DATA_DIR, network });
  const id = await original.share(group.id, group.name, "Owner");
  store.patchGroup(group.id, { sharedGroupId: id }); original.close();
  const path = join(DATA_DIR, "collaboration/identity.json"); unlinkSync(path);
  const repaired = new CollaborationService({ dataDir: DATA_DIR, network });
  const adapter = new CollaborationGroups(store, repaired); close.push(() => { adapter.close(); repaired.close(); });
  expect(() => adapter.recover()).not.toThrow();
  expect(repaired.status()[0]?.blocked).toBe(true);
  expect(existsSync(path)).toBe(false);
  expect(store.appendMessage(group.threadId, { role: "user", kind: "text", text: "Local work still works" }).text).toBe("Local work still works");
});
it("projects shared text into existing groups without exporting private state or replaying bot turns", async () => {
  const remoteDir = mkdtempSync(join(tmpdir(), "hattera-group-projection-")); dirs.push(remoteDir);
  let offline = false;
  const peers = new Map<string, CollaborationService>();
  const network = (origin: string) => ({
    async status(): Promise<PrivateNetworkState> { return { available: true, enabled: true, state: "connected", authorizationUrl: null, origin, message: null, peers: [], peerTransport: true }; },
    async peer(endpoint: string, body: unknown) { if (offline) throw new Error("Fixture offline"); try { return { status: 200, body: await peers.get(endpoint)!.handlePeer(body) }; } catch { return { status: 403, body: {} }; } },
  });
  const store = new Store(() => ({ instanceId: "fixture", model: "fixture" }));
  const bot = store.createBot({ name: "Local coder" }, { seedMessages: false });
  const group = store.createGroup("Feature", [bot.id], false, undefined, { completed: true });
  store.appendMessage(group.threadId, { kind: "text", role: "user", text: "Private old history", at: 1 });
  let adapter: CollaborationGroups;
  const local = new CollaborationService({ dataDir: DATA_DIR, network: network("http://100.64.2.1"), changed: id => adapter?.project(id) });
  const remote = new CollaborationService({ dataDir: remoteDir, network: network("http://100.64.2.2") });
  peers.set("http://100.64.2.1", local); peers.set("http://100.64.2.2", remote);
  adapter = new CollaborationGroups(store, local);
  close.push(() => { adapter.close(); local.close(); remote.close(); });
  const id = await local.share(group.id, group.name, "Alice");
  store.patchGroup(group.id, { sharedGroupId: id }); adapter.recover();
  expect(local.ledger(id).messages()).toHaveLength(0);
  await remote.join(await local.invite(id), "remote-group", "Bob"); await remote.synchronize(id);
  const human = store.appendMessage(group.threadId, { kind: "text", role: "user", text: "Build this feature" });
  expect(local.ledger(id).messages()).toHaveLength(1);
  expect(store.messagesFor(group.threadId).find(message => message.id === human.id)?.shared?.remote).toBe(false);
  const reply = store.appendMessage(group.threadId, { kind: "text", role: "bot", text: "Streaming reply", turnId: "turn", from: { botId: bot.id, name: bot.name, color: bot.color } });
  expect(local.ledger(id).messages()).toHaveLength(1);
  store.patchMessage(group.threadId, reply.id, { text: "Completed reply", turnTerminal: true });
  expect(local.ledger(id).messages()).toHaveLength(2);
  store.appendMessage(group.threadId, { kind: "activity", role: "bot", tool: { name: "bash", input: "provider-secret must stay here" } });
  store.appendMessage(group.threadId, { kind: "text", role: "user", text: 'Attachment message\n\n<file path="C:/private/key.txt" name="key.txt" />' });
  store.appendMessage(group.threadId, { kind: "text", role: "user", text: 'Native attachment\n\n<attached-file path="C:/native/private.txt" name="private.txt" />' });
  await remote.synchronize(id, id);
  const serialized = JSON.stringify(remote.ledger(id).events);
  expect(serialized).toContain("Completed reply");
  expect(serialized).not.toContain("Private old history");
  expect(serialized).not.toContain("provider-secret");
  expect(serialized).not.toContain("C:/private");
  expect(serialized).not.toContain("C:/native");
  expect(remote.status()[0]?.bots).toContainEqual(expect.objectContaining({ name: bot.name }));
  store.patchBot(bot.id, { name: "👩‍💻 Coder", title: "Long title ".repeat(30) });
  await remote.synchronize(id, id);
  expect(remote.status()[0]?.bots).toContainEqual(expect.objectContaining({ name: "👩‍💻 Coder", title: expect.any(String) }));
  const messageId = "from-bob";
  remote.append(id, { type: "message.upsert", topicId: group.threadId, topicTitle: "Feature", messageId, text: "Please run this?", role: "human", authorLabel: "Bob" });
  await remote.synchronize(id, id);
  const received = store.messagesFor(group.threadId).filter(message => message.shared?.messageId === messageId);
  expect(received).toHaveLength(1);
  expect(received[0]).toMatchObject({ text: "Please run this?", relayed: true, sender: { name: "Bob" }, shared: { remote: true, author: "Bob" } });
  expect(received[0]?.sender?.id).toBeUndefined();
  expect(store.bot(bot.id)?.busy).toBeFalsy();
  adapter.recover(); adapter.project(id);
  expect(store.messagesFor(group.threadId).filter(message => message.shared?.messageId === messageId)).toHaveLength(1);
  offline = true;
  const bob = local.ledger(id).members().find(member => member.name === "Bob")!;
  await expect(local.synchronize(id, bob.grantId)).rejects.toThrow(/offline/);
  const queued = store.appendMessage(group.threadId, { kind: "text", role: "user", text: "Durable while disconnected" });
  expect(local.ledger(id).messages()).toContainEqual(expect.objectContaining({ payload: expect.objectContaining({ messageId: queued.id }) }));
  offline = false; await local.synchronize(id, bob.grantId);
  expect(remote.ledger(id).messages()).toContainEqual(expect.objectContaining({ payload: expect.objectContaining({ text: "Durable while disconnected" }) }));
  store.deleteGroup(group.id);
  expect(local.status()[0]?.enabled).toBe(false);
  adapter.recover(); expect(store.group(group.id)).toBeUndefined();
});
